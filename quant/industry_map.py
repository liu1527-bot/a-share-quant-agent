def get_industry(ticker: str, default: str = '其他') -> str:
    """获取股票的申万一级行业。未知归 '其他'。"""
    return INDUSTRY_MAP.get(str(ticker).zfill(6), default)


def get_industry_map() -> dict:
    """返回完整 ticker -> industry 映射 (副本)。"""
    return dict(INDUSTRY_MAP)


def coverage_stats(tickers: list) -> dict:
    """统计某 ticker 列表的行业覆盖率。"""
    classified = sum(1 for t in tickers if str(t).zfill(6) in INDUSTRY_MAP)
    industries = {}
    for t in tickers:
        ind = get_industry(t)
        industries[ind] = industries.get(ind, 0) + 1
    return {
        'total': len(tickers),
        'classified': classified,
        'coverage_pct': classified / len(tickers) * 100 if tickers else 0,
        'industry_counts': dict(sorted(industries.items(), key=lambda x: -x[1])),
    }
